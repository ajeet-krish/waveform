//! Database access for Waveform.
//!
//! Owns the SQLx pool setup, the embedded migration runner (repository-level
//! `migrations/` directory), the shared row models, the wire DTOs, and the
//! entity-generic sync engine (`queries`). Models and DTOs derive
//! `ts_rs::TS` and are exported to `packages/api-types/src/generated.ts`
//! by the `export_ts` test, plus `rules.generated.ts` (the typed
//! `RULE_CONSTANTS` value) by `export_ts_rules`; CI fails when the
//! committed files drift.

pub mod dto;
pub mod models;
pub mod queries;

use std::time::Duration;

use sqlx::migrate::Migrator;
use sqlx::postgres::PgPoolOptions;
use sqlx::PgPool;

pub use models::*;

/// Embedded migrations, applied in filename order by [`run_migrations`].
pub static MIGRATOR: Migrator = sqlx::migrate!("../../migrations");

/// Maximum pooled connections per process.
const MAX_CONNECTIONS: u32 = 10;

/// How long to wait for a free connection before failing.
const ACQUIRE_TIMEOUT: Duration = Duration::from_secs(5);

/// Connect a pool to `database_url` (for example
/// `postgres://waveform:waveform@localhost:5432/waveform`).
pub async fn connect(database_url: &str) -> Result<PgPool, sqlx::Error> {
    PgPoolOptions::new()
        .max_connections(MAX_CONNECTIONS)
        .acquire_timeout(ACQUIRE_TIMEOUT)
        .connect(database_url)
        .await
}

/// Apply all pending migrations. sqlx tracks applied versions in the
/// `_sqlx_migrations` table, so repeat calls are no-ops. Assumes a single
/// instance runs migrations at a time (one Railway service, one CI job):
/// concurrent multi-instance startups can race inside sqlx's migration
/// lock. Production should prefer the explicit `migrate` subcommand over
/// startup migration (`RUN_MIGRATIONS` defaults to false).
pub async fn run_migrations(pool: &PgPool) -> Result<(), sqlx::migrate::MigrateError> {
    MIGRATOR.run(pool).await
}

#[cfg(test)]
mod export_tests {
    use crate::dto::{
        ActivityRules, ApiErrorBody, ApiErrorCode, AuthResponse, BodyRules, LoginRequest, OpAction,
        OpResult, OpStatus, PasswordRules, PullPage, PullRow, PushOp, PushRequest, PushResponse,
        RuleConstants, SetRules, SignupRequest, SyncEntity, SyncLimits,
    };
    use crate::{
        Activity, ActivityType, BodyStats, Challenge, Exercise, ExerciseEntry, Group, GroupMember,
        GroupRole, Kudos, PublicUser, Routine, RoutineEntry, SetEntry, User, WorkoutSession,
    };
    use ts_rs::TS;

    /// Regenerates `packages/api-types/src/generated.ts`. CI runs
    /// `cargo test export_ts` and fails if the committed file drifts from
    /// the Rust models and DTOs.
    #[test]
    fn export_ts() {
        for result in [
            Activity::export(),
            ActivityType::export(),
            BodyStats::export(),
            Challenge::export(),
            Exercise::export(),
            ExerciseEntry::export(),
            Group::export(),
            GroupMember::export(),
            GroupRole::export(),
            Kudos::export(),
            PublicUser::export(),
            Routine::export(),
            RoutineEntry::export(),
            SetEntry::export(),
            User::export(),
            WorkoutSession::export(),
            // Phase 2 wire DTOs.
            SyncEntity::export(),
            OpAction::export(),
            OpStatus::export(),
            PushOp::export(),
            PushRequest::export(),
            OpResult::export(),
            PushResponse::export(),
            PullRow::export(),
            PullPage::export(),
            ApiErrorCode::export(),
            ApiErrorBody::export(),
            SignupRequest::export(),
            LoginRequest::export(),
            AuthResponse::export(),
            // Rule trees.
            SetRules::export(),
            ActivityRules::export(),
            BodyRules::export(),
            SyncLimits::export(),
            PasswordRules::export(),
            RuleConstants::export(),
        ] {
            result.expect("ts-rs export failed");
        }
    }

    /// Regenerates `packages/api-types/src/rules.generated.ts`: a typed
    /// `RULE_CONSTANTS` value derived from `RuleConstants::default()`.
    /// CI runs `cargo test export_ts` (name prefix match) and fails if
    /// the committed file drifts from the Rust defaults.
    #[test]
    fn export_ts_rules() {
        let value =
            serde_json::to_string_pretty(&RuleConstants::default()).expect("serialize rules");
        let source = format!(
            "// This file is generated by `cargo test export_ts_rules` (crates/db). \
             Do not edit it by hand.\n\
             import type {{ RuleConstants }} from \"./generated\";\n\n\
             export const RULE_CONSTANTS: RuleConstants = {value};\n"
        );
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../packages/api-types/src/rules.generated.ts");
        std::fs::write(&path, source).expect("write rules.generated.ts");
    }
}
